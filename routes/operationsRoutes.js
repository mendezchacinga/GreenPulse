router.get("/effluents", operations.requireRole("hssa"), operations.listEffluents);
router.post("/effluents", operations.requireRole("hssa"), operations.createEffluent);
router.get("/effluent-catalog", operations.requireRole("hssa"), operations.listEffluentCatalog);
router.post("/effluent-catalog", operations.requireRole("hssa"), operations.saveEffluentCatalog);
router.get("/catalogs/:type", operations.requireRole("supervisor", "hssa"), operations.catalog);
