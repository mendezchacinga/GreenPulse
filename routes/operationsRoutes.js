router.get("/analytics", operations.requireRole("supervisor", "hssa", "gerencia"), operations.analytics);
router.get("/trends/monthly", operations.requireRole("hssa", "gerencia"), operations.monthlyTrend);
router.get("/audit-log", operations.requireRole("hssa"), operations.auditLog);
router.get("/dashboard", operations.requireRole("supervisor", "hssa", "gerencia"), operations.dashboard);
router.get("/hssa/dashboard", operations.requireRole("hssa"), operations.hssaDashboard);
