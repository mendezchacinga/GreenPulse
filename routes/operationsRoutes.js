router.post("/hssa/users", operations.requireRole("hssa"), operations.createOperationUser);
router.patch("/hssa/users/:email", operations.requireRole("hssa"), operations.updateOperationUser);
router.delete("/hssa/users/:email", operations.requireRole("hssa"), operations.deleteOperationUser);

module.exports = router;
