const express = require("express");
const operations = require("../controllers/operationsController");
const api = require("../controllers/apiController");
const router = express.Router();

router.get("/backup", api.requireAdmin, operations.backup);
router.use(api.requireUser);
router.get("/profile", operations.profile);
router.post("/losses", operations.requireRole("operario", "supervisor"), operations.createLoss);
router.get("/losses", operations.requireRole("operario", "supervisor", "hssa", "gerencia"), operations.listLosses);
router.get("/losses/:id/history", operations.requireRole("operario", "supervisor", "hssa", "gerencia"), operations.lossHistory);
router.patch("/losses/:id", operations.requireRole("supervisor", "hssa"), operations.validateLoss);
router.get("/production", operations.requireRole("supervisor"), operations.listProduction);
router.post("/production", operations.requireRole("supervisor"), operations.saveProduction);
router.get("/stoppages", operations.requireRole("supervisor"), operations.listStoppages);
router.post("/stoppages", operations.requireRole("supervisor"), operations.createStoppage);
router.get("/zones", operations.requireRole("supervisor", "hssa"), operations.listZones);
router.get("/movements", operations.requireRole("supervisor", "hssa"), operations.listMovements);
router.post("/storage", operations.requireRole("supervisor"), operations.createMovement("entry"));
